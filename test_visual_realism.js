'use strict';
const assert = require('assert');
const Renderer = require('./js/canvas');
const r = new Renderer(null, {enableParticles:true});
const frame = {state:'ACTIVE_MASHING', totalTaps:1, activeHand:'left', leftThumbStrain:0.5, rightThumbStrain:0.1};
r._updateGripAnimation(frame, 1/60);
assert(r.leftSqueeze > 0 && r.rightSqueeze === 0, 'left input must move only the left grip');
assert(r._leftPadPressure > 0 && r._rightPadPressure > 0 && r._leftPadPressure > r._rightPadPressure, 'active hand must compress more strongly');
r._updateGripAnimation({...frame,totalTaps:2,activeHand:'left'}, 1/60);
assert.strictEqual(r.leftSqueeze,1,'a repeated tap must refresh the same hand');
r._updateGripAnimation({...frame,totalTaps:3,activeHand:'right'}, 1/60);
assert.strictEqual(r.rightSqueeze,1,'right input must move the right grip');
r.particlePool.spawn('dust', 1, 2, 1);
const particles = JSON.stringify(r.particlePool.particles);
const keys=['_currentDamagePct','_currentStrain','_currentTierId','_currentWingAngle','_currentHingeY','_currentBendDeg','leftSqueeze','rightSqueeze','tapPump','_leftPadPressure','_rightPadPressure'];
const before=keys.map(k=>r[k]);
const card=r.renderOffscreenCard({tier:{id:'titanium'},damagePct:75,bendAngleDeg:24,survived:false});
assert.deepStrictEqual(keys.map(k=>r[k]),before,'card export must not change live grip or bend');
assert.strictEqual(JSON.stringify(r.particlePool.particles),particles,'card export must not alter live particles');
assert.strictEqual(card.width,1200); assert.strictEqual(card.height,630);
console.log('Grip synchronization and isolated 1200x630 card export verified.');
