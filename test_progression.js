'use strict';
const assert = require('assert');
const {createProgression} = require('./js/ui');
const records = new Map();
const storage={getItem:key=>records.get(key)??null,setItem:(key,value)=>records.set(key,value)};
let p=createProgression(storage);
assert(p.isUnlocked('standard')&&!p.isUnlocked('dust')&&!p.isUnlocked('titanium'));
assert.strictEqual(p.recordWin('titanium',10),null,'locked levels cannot record wins');
assert(p.recordWin('standard',12).unlockedNext);
assert(p.isUnlocked('dust')&&!p.isUnlocked('titanium'));
assert(p.recordWin('dust',14).unlockedNext);
assert(p.isUnlocked('titanium'));
assert(p.recordWin('titanium',17).newBest);
assert(!p.recordWin('standard',15).newBest);
assert.strictEqual(p.getBest('standard'),12);
assert(p.recordWin('standard',11).newBest);
p=createProgression(storage);
assert.strictEqual(p.getUnlockedCount(),3);
assert.strictEqual(p.getBest('standard'),11);
assert.strictEqual(p.recordWin('standard',NaN),null);
const broken={getItem(){throw Error('blocked')},setItem(){throw Error('blocked')}};
const session=createProgression(broken);
assert(!session.isPersistent());
assert.strictEqual(session.recordWin('standard',10).saved,false);
assert(session.isUnlocked('dust'));
const invalid=new Map([['bend-test.progress.v1','bad-json']]);
const malformed=createProgression({getItem:k=>invalid.get(k)??null,setItem:(k,v)=>invalid.set(k,v)});
malformed.recordWin('standard',10);
assert.strictEqual(invalid.get('bend-test.progress.v1'),'bad-json','preserve unknown stored records');
console.log('Sequential unlocks, personal bests, reload persistence and storage failures verified.');
