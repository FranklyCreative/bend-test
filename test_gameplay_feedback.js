'use strict';
const assert=require('assert');
const Engine=require('./js/engine');
const e=new Engine({interactiveAssist:true,runDuration:25,enableAudio:false,enableHaptics:false});
let now=10;e._getNow=()=>now;
e.startActiveMashing();
const intact=e.getRenderSnapshot().yieldThreshold;
e.forceDamagePct(50);
const weakened=e.getRenderSnapshot().yieldThreshold;
assert(weakened<intact,'damage must lower the displayed damage threshold');
assert.strictEqual(weakened,e.getYieldThreshold(),'display and physics threshold must agree');
e.force=weakened;assert(!e.getRenderSnapshot().forceAboveYield);
e.force=weakened+0.01;assert(e.getRenderSnapshot().forceAboveYield);
e.registerTap('left','keyboard');now+=0.1;e.registerTap('right','keyboard');
assert(e.getRenderSnapshot().comboActive);
assert(e.getRenderSnapshot().comboRemainingSec>0);
now+=0.41;assert(!e.getRenderSnapshot().comboActive,'combo feedback must expire');
e.registerTap('left','keyboard');now+=0.1;e.registerTap('right','keyboard');
assert(e.getRenderSnapshot().comboActive);
now+=0.1;e.registerTap('right','keyboard');assert(!e.getRenderSnapshot().comboActive,'same hand ends alternation');
e.setTier('dust');assert(!e.getRenderSnapshot().comboActive,'switching device resets feedback');
console.log('Yield marker accuracy and time-limited combo feedback verified.');
